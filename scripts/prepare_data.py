"""Generate the bot's rule and example files from the QC review spreadsheet.

    python scripts/prepare_data.py [--xlsx data/QC_Review_Analysis_Jun-Oct_2026.xlsx]

Writes:
    rules.yaml               from "Caption rules"
    clients/<CLIENT>.yaml    from "Client rules" (your "overrides:" block is kept on rerun)
    data/examples.csv        from "Caption mistakes (59)"
    data/exceptions.yaml     from "Accepted exceptions"
    glossary.txt             empty starter, only if it doesn't exist yet
"""

from __future__ import annotations

import argparse
import csv
import datetime as dt
import re
import sys
from pathlib import Path

import yaml
from openpyxl import load_workbook

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.clients.workbook import clean, client_for, find_sheet, read_rows  # noqa: E402,F401
from src.config import load_config, load_yaml, normalize_client_code, resolve_path  # noqa: E402
from src.utils.timecode import TimecodeError, infer_fps, parse_range  # noqa: E402

DEFAULT_XLSX = ROOT / "data" / "QC_Review_Analysis_Jun-Oct_2026.xlsx"

EXAMPLE_COLUMNS = ["client", "task_name", "video_timestamp", "start_sec", "end_sec",
                   "editor_wrote", "should_be", "category", "comment_text"]

GLOSSARY_STARTER = """\
# glossary.txt - words the spelling check must never flag (brand names, people, products, jargon).
# Also passed to Whisper as a hint so it spells these terms correctly (Phase 4).
#
# Format: one term per line. Blank lines and lines starting with # are ignored.
#   Danja                 plain term: accepted in any capitalization
#   =Mark McGwire         "=" prefix: forced spelling, must appear exactly like this
#   =YouTube              (so "Youtube" or "youtube" gets flagged)
"""

_LEADING_TIME = re.compile(r"^(\d+(?::\d+)+)\s+")
_EXAMPLE_SPLIT = re.compile(r";\s+(?=[A-Za-z0-9_]+:)")


def show(path: Path) -> Path:
    """Path relative to the project when possible, for tidy output."""
    try:
        return path.relative_to(ROOT)
    except ValueError:
        return path


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def dump_yaml(data) -> str:
    return yaml.safe_dump(data, allow_unicode=True, sort_keys=False, width=100)


def build_rules(rows: list[dict], source: str) -> str:
    counters: dict[str, int] = {}
    rules = []
    for row in rows:
        area = row["area"]
        counters[area] = counters.get(area, 0) + 1
        rules.append({
            "id": f"{slug(area)}_{counters[area]}",
            "area": area,
            "rule": row["rule"],
            "examples": [e.strip() for e in _EXAMPLE_SPLIT.split(row.get("example", "")) if e.strip()],
        })
    header = (f"# Caption rules. Generated by scripts/prepare_data.py from the \"Caption rules\" sheet.\n"
              f"# Regenerating overwrites this file, so make lasting changes in the spreadsheet.\n")
    body = {"version": dt.date.today().isoformat(), "source": source, "rules": rules}
    return header + dump_yaml(body)


def build_client_files(rows: list[dict], clients_dir: Path) -> list[str]:
    written = []
    for row in rows:
        code = normalize_client_code(row["client_code"])
        path = clients_dir / f"{code}.yaml"
        kept = load_yaml(path) if path.exists() else {}
        header = (
            f"# Client rules for {code}. Generated by scripts/prepare_data.py from the \"Client rules\" sheet.\n"
            "# \"client\", \"project\" and \"notes\" are rewritten on every run. Everything else is yours\n"
            "# and is kept when this file is regenerated:\n"
            "#   glossary:   extra glossary.txt lines for this client only, e.g. [\"=Mark McGwire\"]\n"
            "#   overrides:  same structure as \"checks:\" in config.yaml, e.g.\n"
            "#                 too_short:\n"
            "#                   min_words: 3\n"
            "#   ocr:        where this client's burned-in captions are; same keys as \"ocr:\" in config.yaml, e.g.\n"
            "#                 region: {left: 0.05, top: 0.68, width: 0.9, height: 0.27}\n"
            "#                 ignore_patterns: ['day \\d+']\n"
        )
        body = {
            "client": code,
            "project": row.get("project (from task name)", ""),
            "notes": row.get("client-specific rule", ""),
        }
        body.update({k: v for k, v in kept.items() if k not in body})
        body["overrides"] = body.get("overrides") or {}
        write_text(path, header + dump_yaml(body))
        written.append(code)
    return written


def build_examples(rows: list[dict], default_fps: float) -> tuple[list[dict], list[str]]:
    examples, problems = [], []
    for row in rows:
        stamp = row.get("video_timestamp", "")
        start = end = ""
        if stamp:
            try:
                s, e = parse_range(stamp, fps=infer_fps(stamp, default_fps))
                start = f"{s:.3f}"
                end = f"{e:.3f}" if e is not None else ""
            except TimecodeError as exc:
                problems.append(str(exc))
        examples.append({
            "client": client_for(row),
            "task_name": row.get("task_name", ""),
            "video_timestamp": stamp,
            "start_sec": start,
            "end_sec": end,
            "editor_wrote": row.get("editor_wrote", ""),
            "should_be": row.get("should_be", ""),
            "category": row.get("category", ""),
            "comment_text": row.get("comment_text", ""),
        })
    return examples, problems


def write_examples(path: Path, examples: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=EXAMPLE_COLUMNS, lineterminator="\n")
        writer.writeheader()
        writer.writerows(examples)


def build_exceptions(rows: list[dict], source: str) -> str:
    items = []
    for row in rows:
        raw_client = row.get("client", "")
        text = row.get("what you accepted", "")
        item = {"client": None if raw_client.startswith("(") else normalize_client_code(raw_client)}
        match = _LEADING_TIME.match(text)
        if match:
            item["timestamp"] = match.group(1)
            text = text[match.end():]
        if len(text) >= 2 and text[0] == text[-1] == '"':
            text = text[1:-1]
        item["note"] = text
        items.append(item)
    header = ("# Accepted exceptions: things the reviewer looked at and accepted.\n"
              "# Generated by scripts/prepare_data.py from the \"Accepted exceptions\" sheet.\n"
              "# client: null means a general comment, not tied to one client.\n")
    return header + dump_yaml({"source": source, "exceptions": items})


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--xlsx", type=Path, default=DEFAULT_XLSX, help="QC review spreadsheet")
    parser.add_argument("--config", type=Path, default=None, help="config file (default: config.yaml)")
    args = parser.parse_args(argv)

    if not args.xlsx.is_file():
        print(f"error: spreadsheet not found: {args.xlsx}", file=sys.stderr)
        return 2

    config = load_config(args.config)
    workbook = load_workbook(args.xlsx, read_only=True, data_only=True)
    source = args.xlsx.name

    rules_path = resolve_path(config, "rules_file")
    rule_rows = read_rows(find_sheet(workbook, "Caption rules"))
    write_text(rules_path, build_rules(rule_rows, source))
    print(f"wrote {show(rules_path)} ({len(rule_rows)} rules)")

    clients = build_client_files(read_rows(find_sheet(workbook, "Client rules")),
                                 resolve_path(config, "clients_dir"))
    print(f"wrote {len(clients)} client files: {', '.join(clients)}")

    examples, problems = build_examples(read_rows(find_sheet(workbook, "Caption mistakes")),
                                        config.get("timecode", {}).get("fps", 30))
    examples_path = resolve_path(config, "examples_file")
    write_examples(examples_path, examples)
    print(f"wrote {show(examples_path)} ({len(examples)} examples)")
    for problem in problems:
        print(f"  warning: timestamp not converted: {problem}")

    exc_rows = read_rows(find_sheet(workbook, "Accepted exceptions"))
    exceptions_path = resolve_path(config, "exceptions_file")
    write_text(exceptions_path, build_exceptions(exc_rows, source))
    print(f"wrote {show(exceptions_path)} ({len(exc_rows)} exceptions)")

    glossary_path = resolve_path(config, "glossary_file")
    if glossary_path.exists():
        print(f"kept existing {show(glossary_path)}")
    else:
        write_text(glossary_path, GLOSSARY_STARTER)
        print(f"wrote {show(glossary_path)} (empty starter)")

    workbook.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
